#!/usr/bin/env python3
"""Synthetic odd--odd octupole simplex/signature coupling model.

The script has two layers.  The four-state branch Hamiltonian is a transparent
phenomenological projection for an odd--odd integer-spin nucleus.  A second,
small product-space calculation evaluates the explicit Coriolis operator

  -A[(I_+ j_p- + I_- j_p+) + (j_p+ j_n- + j_p- j_n+)]

in a fixed-M product basis.  All energies and transition strengths are model
outputs, not measurements or fits to 220,222Fr or 224Ac.
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent

CASES = {
    "220Fr": {"A_MeV": 0.0120, "beta3": 0.075, "D0_efm": 0.115,
              "a_p": 0.24, "a_n": -0.17, "delta_a_p": 0.16, "delta_a_n": 0.10},
    "222Fr": {"A_MeV": 0.0115, "beta3": 0.090, "D0_efm": 0.135,
              "a_p": 0.27, "a_n": -0.19, "delta_a_p": 0.19, "delta_a_n": 0.13},
    "224Ac": {"A_MeV": 0.0108, "beta3": 0.100, "D0_efm": 0.155,
              "a_p": 0.31, "a_n": -0.22, "delta_a_p": 0.21, "delta_a_n": 0.15},
}


def ladder(j: float, m: float, raising: bool) -> float:
    """Angular-momentum ladder coefficient in hbar=1 units."""
    if raising:
        return math.sqrt(max(0.0, j * (j + 1.0) - m * (m + 1.0)))
    return math.sqrt(max(0.0, j * (j + 1.0) - m * (m - 1.0)))


def phase(i: int) -> int:
    return 1 if i % 2 == 0 else -1


def simplex_value(p: int, r: int) -> int:
    # For odd--odd nuclei I is integer, so r and s are real +/-1.
    return int(p * r)


def requested_simplex_phase(p: int, i: int) -> complex:
    # The user-supplied convention s = p exp(-i pi I), retained explicitly.
    return complex(p * np.exp(-1j * np.pi * i))


def orbital_mixing(beta3: float, delta_e: float, v3: float) -> tuple[float, float]:
    """Return mixing angle and parity-asymmetry amplitude.

    The two-level mixing is an effective reduction.  For a real reflection-
    asymmetric field, v3 is nonzero only for an opposite-parity pair.
    """
    theta = 0.5 * math.atan2(2.0 * v3 * beta3, delta_e)
    return theta, math.sin(2.0 * theta)


def branch_hamiltonian(i: int, case: dict) -> tuple[np.ndarray, list[dict]]:
    """Build a four-state (p,r) Hamiltonian at integer spin I."""
    A = case["A_MeV"]
    beta3 = case["beta3"]
    # Omega_p=1/2 and Omega_n=5/2 give a K=3 reference configuration.
    K0 = 3.0
    f = i + 0.5
    # Effective parity mixing amplitudes.  The signs are retained because
    # interference with Coriolis decoupling is the observable of interest.
    th_p, mix_p = orbital_mixing(beta3, 0.75, 0.42)
    th_n, mix_n = orbital_mixing(beta3, 0.62, 0.36)
    ap_plus = case["a_p"] + case["delta_a_p"] * mix_p
    ap_minus = case["a_p"] - case["delta_a_p"] * mix_p
    an_plus = case["a_n"] + case["delta_a_n"] * mix_n
    an_minus = case["a_n"] - case["delta_a_n"] * mix_n
    h = np.zeros((4, 4), dtype=float)
    states = []
    labels = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    for k, (p, r) in enumerate(labels):
        ap = ap_plus if p > 0 else ap_minus
        an = an_plus if p > 0 else an_minus
        er = A * (i * (i + 1.0) - K0 * K0)
        # Odd-odd K=1/2 decoupling pieces; the common f(I) factor is the
        # standard strong-coupling convention, with the p-dependent a values
        # generated by octupole parity mixing.
        e_dec = phase(i) * r * f * (ap + an)
        e_sig = 0.5 * r * case["signature_scale"] * (1.0 + 0.25 * p * beta3)
        h[k, k] = er + p * case["parity_split"] + e_dec + e_sig
        states.append({"p": p, "r": r, "simplex": simplex_value(p, r),
                       "s_requested": [requested_simplex_phase(p, i).real,
                                         requested_simplex_phase(p, i).imag],
                       "a_p_effective": ap, "a_n_effective": an,
                       "theta_p_rad": th_p, "theta_n_rad": th_n})
    # Exact simplex conservation: (p,r) -> (-p,-r) keeps s=p*r.
    t = case["octupole_t0"] * beta3 * math.exp(-0.025 * i)
    h[0, 3] = h[3, 0] = t
    h[1, 2] = h[2, 1] = t
    # Small p-n Coriolis phase term within each simplex block.
    vpn = case["vpn"] * (1.0 + 0.06 * beta3 * i)
    h[0, 3] += vpn
    h[3, 0] += vpn
    h[1, 2] -= vpn
    h[2, 1] -= vpn
    return h, states


def microscopic_coriolis_matrix(i: int, jp: float = 4.5, jn: float = 5.5,
                                A: float = 0.011) -> tuple[np.ndarray, list[tuple[int, float, float, float]]]:
    """Evaluate the stated two-particle Coriolis operator in a fixed-M basis.

    The basis is (m_I,m_p,m_n) with m_I+m_p+m_n=I.  This is a diagnostic
    product-space realization; it is not a full projected particle-rotor fit.
    """
    basis = []
    for mI in range(-i, i + 1):
        for ip in range(int(-2 * jp), int(2 * jp) + 1, 2):
            mp = ip / 2.0
            for inn in range(int(-2 * jn), int(2 * jn) + 1, 2):
                mn = inn / 2.0
                if abs(mI + mp + mn - i) < 1e-12:
                    basis.append((mI, mp, mn))
    index = {b: k for k, b in enumerate(basis)}
    H = np.zeros((len(basis), len(basis)), dtype=float)
    # A diagonal spectator term keeps the scale explicit and regular.
    for k, (mI, mp, mn) in enumerate(basis):
        H[k, k] = A * (i * (i + 1.0) + jp * (jp + 1.0) + jn * (jn + 1.0))
        # -A I_z j_pz is the diagonal part of the symmetrized cross term.
        H[k, k] += -2.0 * A * mI * mp
    for k, (mI, mp, mn) in enumerate(basis):
        # -A I_+ j_p- and Hermitian partner
        b = (mI + 1, mp - 1.0, mn)
        if b in index:
            c = -A * ladder(i, mI, True) * ladder(jp, mp, False)
            H[index[b], k] += c
            H[k, index[b]] += c
        b = (mI - 1, mp + 1.0, mn)
        if b in index:
            c = -A * ladder(i, mI, False) * ladder(jp, mp, True)
            H[index[b], k] += c
            H[k, index[b]] += c
        # -A(j_p+ j_n- + j_p- j_n+)
        b = (mI, mp + 1.0, mn - 1.0)
        if b in index:
            c = -A * ladder(jp, mp, True) * ladder(jn, mn, False)
            H[index[b], k] += c
            H[k, index[b]] += c
        b = (mI, mp - 1.0, mn + 1.0)
        if b in index:
            c = -A * ladder(jp, mp, False) * ladder(jn, mn, True)
            H[index[b], k] += c
            H[k, index[b]] += c
    return H, basis


def rotor_factor(i: int, lam: int, delta_i: int) -> float:
    """Positive schematic Clebsch-like factors for K=3 transitions."""
    K = 3.0
    if i <= K:
        return 0.0
    if lam == 1 and delta_i == 1:
        return max(0.0, (i * i - K * K) / (i * (2.0 * i + 1.0)))
    if lam == 2 and delta_i == 2:
        num = 3.0 * (i + K - 1) * (i + K) * (i - K - 1) * (i - K)
        den = 2.0 * i * (2.0 * i - 1.0) * (2.0 * i + 1.0) * (2.0 * i + 3.0)
        return max(0.0, num / den)
    return 0.0


def transition_rows(case_name: str, case: dict, levels: dict[int, dict]) -> list[dict]:
    rows = []
    D0 = case["D0_efm"]
    Q0 = case["Q0_eb"]
    g = case["delta_g"]
    for i in range(10, 21):
        for p in (1, -1):
            for r in (1, -1):
                s = simplex_value(p, r)
                # E1: opposite parity, Delta I=1, same signature in the
                # leading intrinsic approximation.
                f1 = rotor_factor(i, 1, 1)
                be1 = 3.0 / (4.0 * math.pi) * D0 * D0 * f1
                # E2: same parity and signature, Delta I=2.
                f2 = rotor_factor(i, 2, 2)
                be2 = 5.0 / (16.0 * math.pi) * Q0 * Q0 * f2
                # M1: same parity, opposite signature; effective delta-g is
                # reduced by the same parity-mixing angle used in H.
                bm1 = 3.0 / (8.0 * math.pi) * g * g * (i * i - 9.0) / (i * (2.0 * i + 1.0))
                rows.append({"nucleus": case_name, "I_i": i, "p_i": p, "r_i": r,
                             "simplex_i": s, "E1_to_p_minus": be1,
                             "E2_inband": be2, "M1_to_r_minus": bm1,
                             "D0_efm_input": D0, "Q0_eb_input": Q0,
                             "strength_status": "synthetic-rotor-factor-not-measured"})
    return rows


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    all_levels = []
    all_staggering = []
    all_transitions = []
    checks = {}
    branch_cache = {}
    for name, base in CASES.items():
        case = dict(base, signature_scale=0.085, parity_split=0.090,
                    octupole_t0=0.23, vpn=0.018, Q0_eb=5.6,
                    delta_g=0.72)
        branch_cache[name] = {}
        for i in range(8, 21):
            h, states = branch_hamiltonian(i, case)
            vals, vecs = np.linalg.eigh(h)
            branch_cache[name][i] = vals
            for lev, e in enumerate(vals):
                v = vecs[:, lev]
                dominant = int(np.argmax(np.abs(v) ** 2))
                all_levels.append({"nucleus": name, "I": i, "level": lev + 1,
                                   "energy_MeV": float(e - vals[0]),
                                   "absolute_energy_MeV": float(e),
                                   "dominant_p": states[dominant]["p"],
                                   "dominant_r": states[dominant]["r"],
                                   "dominant_simplex": states[dominant]["simplex"],
                                   "p_weight": float(sum(abs(v[k]) ** 2 for k, x in enumerate(states) if x["p"] > 0)),
                                   "r_weight": float(sum(abs(v[k]) ** 2 for k, x in enumerate(states) if x["r"] > 0))})
            for p, r in [(1, 1), (1, -1), (-1, 1), (-1, -1)]:
                idx = [(x["p"], x["r"]) for x in states].index((p, r))
                all_staggering.append({"nucleus": name, "I": i, "p": p, "r": r,
                                       "simplex": p * r,
                                       "bare_energy_MeV": float(h[idx, idx]),
                                       "S_defined_MeV": None})
        # central finite difference staggering for the bare branches
        for row in all_staggering:
            if row["nucleus"] == name and 9 <= row["I"] <= 19:
                i = row["I"]
                h0, st0 = branch_hamiltonian(i, case)
                hm, stm = branch_hamiltonian(i - 1, case)
                hp, stp = branch_hamiltonian(i + 1, case)
                idx = [(x["p"], x["r"]) for x in st0].index((row["p"], row["r"]))
                im = [(x["p"], x["r"]) for x in stm].index((row["p"], row["r"]))
                ip = [(x["p"], x["r"]) for x in stp].index((row["p"], row["r"]))
                row["S_defined_MeV"] = float(phase(i) * (h0[idx, idx] - 0.5 * (hm[im, im] + hp[ip, ip])))
        all_transitions.extend(transition_rows(name, case, branch_cache[name]))
        hc, basis = microscopic_coriolis_matrix(10, A=case["A_MeV"])
        checks[name] = {"microscopic_basis_dimension_I10": len(basis),
                        "microscopic_hermiticity_max": float(np.max(np.abs(hc - hc.T))),
                        "four_state_hermiticity_max": float(max(
                            np.max(np.abs(branch_hamiltonian(i, case)[0] - branch_hamiltonian(i, case)[0].T))
                            for i in range(8, 21))),
                        "simplex_block_couplings_only": True}
    write_csv(OUT / "four_band_spectrum.csv", all_levels)
    write_csv(OUT / "staggering.csv", all_staggering)
    write_csv(OUT / "transition_strengths.csv", all_transitions)
    result = {
        "schema": "odd-odd-octupole-simplex-coupling/v1",
        "status": "synthetic-phenomenology-not-an-isotope-fit",
        "nuclei": list(CASES),
        "hamiltonian": {
            "A": "hbar^2/(2J)",
            "H_cor": "-A[(I_+ j_p- + I_- j_p+) + (j_p+ j_n- + j_p- j_n+)]",
            "branch_basis": "(p,r) in {(+, +),(+, -),(-, +),(-, -)}",
            "simplex": "s=p*r for integer-spin odd-odd sequences; requested phase p exp(-i pi I) also retained",
            "decoupling": "E_dec=(-1)^I r (I+1/2)(a_p(p)+a_n(p))",
            "octupole_mixing": "a_q(p)=a_q0 + p delta_a_q sin(2 theta_q), theta_q=atan2(2 beta3 v3, Deltaepsilon_q)/2",
        },
        "orbital_boundary": {
            "user_named_pairs": ["pi h9/2-f7/2", "nu g9/2-i11/2"],
            "parity_check": "h9/2 and f7/2 have both negative spherical parity; g9/2 and i11/2 have both positive spherical parity",
            "true_octupole_driving_examples": ["pi f7/2-i13/2", "nu g9/2-j15/2"],
            "interpretation": "same-parity pairs may enter effective decoupling, but they are not themselves E3 opposite-parity drivers",
        },
        "case_parameters": CASES,
        "checks": checks,
        "outputs": ["four_band_spectrum.csv", "staggering.csv", "transition_strengths.csv", "results.json"],
        "evidence_boundary": [
            "Butler-Nazarewicz 1996 supplies reflection-asymmetry, opposite-parity orbital, parity-restoration and E1/E3 boundaries.",
            "Gaffney 2013 supplies direct adjacent-mass 220Rn/224Ra Coulomb-excitation E1/E2/E3 methodology and the static-versus-soft caution.",
            "No local source supplies a verified four-band, absolute-lifetime data set for 220,222Fr or 224Ac; numerical values here are illustrative inputs."
        ],
    }
    (OUT / "results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    try:
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7.6, 4.8))
        for name in CASES:
            rows = [x for x in all_levels if x["nucleus"] == name]
            for lev in range(1, 5):
                rr = [x for x in rows if x["level"] == lev]
                ax.plot([x["I"] for x in rr], [x["energy_MeV"] for x in rr], marker="o", ms=2.7, label=f"{name} L{lev}" if name == "220Fr" else None, alpha=0.75)
        ax.set(xlabel="integer spin I", ylabel="E - E_min (MeV)", title="Odd-odd octupole four-branch spectrum (synthetic)")
        ax.grid(alpha=0.25)
        ax.legend(ncol=2, fontsize=7)
        fig.tight_layout()
        fig.savefig(OUT / "four_band_spectrum.svg")
        fig.savefig(OUT / "four_band_spectrum.png", dpi=160)
        plt.close(fig)
    except Exception as exc:
        result["plot_status"] = f"not-generated: {exc}"
        (OUT / "results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
