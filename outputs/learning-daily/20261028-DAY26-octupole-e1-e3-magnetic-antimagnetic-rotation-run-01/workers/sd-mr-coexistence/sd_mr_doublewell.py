#!/usr/bin/env python3
"""Toy, reproducible SD/MR two-well comparison for the Pb A~190 region.

This is a transparent scale model, not a self-consistent HFB/TAC calculation.
It generates a deformation-coordinate double well, rotor B(E2) estimates,
shears B(M1) estimates, and illustrative dynamic-inertia trajectories.
The numerical inputs are declared below and are deliberately separated from
experimental source claims.
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parent
A = 194.0
Z = 82.0
R0 = 1.2 * A ** (1.0 / 3.0)  # fm
Q_COEFF = 3.0 / math.sqrt(5.0 * math.pi) * Z * R0**2 / 100.0  # eb / beta2
E2_WU = (R0**4 / 5.0) / 10000.0  # e^2 b^2, standard A-dependent E2 W.u.


def double_well(beta: float, beta_n: float, beta_sd: float, scale: float, tilt: float) -> float:
    """MeV: V = scale*(beta-beta_n)^2*(beta-beta_sd)^2 + tilt*(beta-beta_n)."""
    return scale * (beta - beta_n) ** 2 * (beta - beta_sd) ** 2 + tilt * (beta - beta_n)


def rotor_c2(I: float) -> float:
    """Rough high-spin Clebsch factor for a K=0, ΔI=2 E2 transition."""
    return I * (I - 1.0) / ((2.0 * I - 1.0) * (2.0 * I + 1.0))


def b_e2(Q0_eb: float, I: float) -> float:
    return 5.0 / (16.0 * math.pi) * Q0_eb**2 * rotor_c2(I)


def b_m1(g_eff: float, j_eff: float, theta_deg: float) -> float:
    return 3.0 / (8.0 * math.pi) * (g_eff * j_eff * math.sin(math.radians(theta_deg))) ** 2


def main() -> None:
    beta_n, beta_sd = 0.10, 0.50
    # At beta=0.30 the untilted barrier is scale*0.0016 = 0.96 MeV.
    scale, tilt = 600.0, 0.0
    reported_qt_sd = 20.0  # eb: source-reported SD Qt comparison, not generated by beta2.
    q0_n, q0_sd = Q_COEFF * beta_n, Q_COEFF * beta_sd

    pes = []
    for k in range(101):
        beta = -0.02 + k * 0.0072
        pes.append({"beta2": beta, "V_MeV": double_well(beta, beta_n, beta_sd, scale, tilt)})

    rows = []
    # Illustrative spin grid; values are model controls, not a band evaluation.
    for I in range(15, 46):
        theta = max(20.0, 90.0 - 1.9 * (I - 15))
        j2_sd = 95.0 + 2.0 * math.sin((I - 15.0) / 5.0)
        j2_mr = 42.0 * math.exp(-(I - 15.0) / 19.0) + 7.0
        rows.append(
            {
                "I_hbar": I,
                "theta_mr_deg": theta,
                "J2_SD_hbar2_per_MeV": j2_sd,
                "J2_MR_hbar2_per_MeV": j2_mr,
                "B_M1_MR_muN2": b_m1(0.80, 6.5, theta),
                "B_E2_MR_e2b2": b_e2(q0_n, I),
                "B_E2_MR_WU": b_e2(q0_n, I) / E2_WU,
                "B_E2_SD_e2b2": b_e2(reported_qt_sd, I),
                "B_E2_SD_WU": b_e2(reported_qt_sd, I) / E2_WU,
            }
        )

    with (ROOT / "deformation_pes.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=pes[0].keys())
        w.writeheader()
        w.writerows(pes)
    with (ROOT / "sd_mr_observables.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=rows[0].keys())
        w.writeheader()
        w.writerows(rows)

    summary = {
        "model_status": "toy_scale_model_not_experiment",
        "nucleus_scale": "A=194, Z=82; parameters are transferable only as an illustrative comparison",
        "equations": {
            "PES": "V(beta2)=600*(beta2-0.10)^2*(beta2-0.50)^2 MeV",
            "Q0": "Q0=(3/sqrt(5*pi))*Z*R0^2*beta2; R0=1.2*A^(1/3) fm",
            "B_E2": "B(E2)=5/(16*pi)*Q0^2*I(I-1)/((2I-1)*(2I+1))",
            "B_M1": "B(M1)=3/(8*pi)*(g_eff*j_eff*sin(theta))^2",
            "J2": "J2_SD=95+2*sin((I-15)/5); J2_MR=42*exp(-(I-15)/19)+7",
        },
        "inputs": {
            "beta2_normal": beta_n,
            "beta2_sd": beta_sd,
            "well_barrier_at_beta2_0.30_MeV": double_well(0.30, beta_n, beta_sd, scale, tilt),
            "Q0_from_beta_normal_eb": q0_n,
            "Q0_from_beta_sd_eb": q0_sd,
            "reported_SD_Qt_input_eb": reported_qt_sd,
            "E2_Weisskopf_unit_e2b2": E2_WU,
            "MR_g_eff": 0.80,
            "MR_j_eff_hbar": 6.5,
        },
        "consistency_check": {
            "reported_Qt_over_Q0_from_beta_sd": reported_qt_sd / q0_sd,
            "interpretation": "Qt~20 eb and beta2~0.50 are not mutually consistent under this liquid-drop conversion; retain them as separate reported/model quantities.",
        },
        "source_boundary": [
            "Astier et al., Z Phys A 358 (1997) 195-196, DOI 10.1007/s002180050305: same-193Pb SD and dipole-band observation.",
            "van Severen et al., Phys Lett B 434 (1998) 14-20, DOI 10.1016/S0370-2693(98)00819-3: SD Qt comparison in 193-196Pb.",
            "Hubel, Prog Part Nucl Phys 54 (2005) 1-69, DOI 10.1016/j.ppnp.2004.06.002: Pb-region MR review; review-level, not an independent lifetime dataset.",
        ],
        "reproducibility": "python3 sd_mr_doublewell.py",
    }
    (ROOT / "sd_mr_model_summary.json").write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main()
