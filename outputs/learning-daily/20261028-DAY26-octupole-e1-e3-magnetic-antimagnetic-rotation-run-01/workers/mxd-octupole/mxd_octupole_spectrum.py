#!/usr/bin/env python3
"""Toy MχD + octupole-coupling spectrum and transition-network generator.

This is a transparent diagnostic model, not a 133Ce/135Nd fit.  It diagonalizes
four basis states for each spin and configuration family:

    |p, chi=+>, |p, chi=->, |opposite p, chi=+>, |opposite p, chi=->

The opposite-parity copy is an octupole-phonon doorway at E_oct.  A same-
chirality coupling v_oct mixes the two parity sectors.  E2 and M1 operators
act within one parity sector; E1 and E3 operators connect opposite parity
sectors.  The resulting CSV files are intended to expose which signatures
are generated by configuration offsets and which require an octupole doorway.

Only numpy is required.  Re-run from this directory with:

    python3 mxd_octupole_spectrum.py
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np


OUT = Path(__file__).resolve().parent


FAMILIES = [
    # The offsets are schematic.  They are deliberately separated from the
    # source values so that no generated number is mistaken for data.
    {"name": "1qp", "parity": 1, "base_mev": 0.00, "gamma_deg": 17.5,
     "delta_chiral_mev": 0.10, "e_oct_mev": 1.20, "v_oct_mev": 0.00,
     "e1_scale": 0.00},
    {"name": "3qp_pos", "parity": 1, "base_mev": 0.48, "gamma_deg": 17.5,
     "delta_chiral_mev": 0.10, "e_oct_mev": 1.20, "v_oct_mev": 0.12,
     "e1_scale": 0.15},
    {"name": "3qp_neg", "parity": -1, "base_mev": 0.82, "gamma_deg": 15.2,
     "delta_chiral_mev": 0.40, "e_oct_mev": 1.20, "v_oct_mev": 0.12,
     "e1_scale": 0.20},
    {"name": "5qp", "parity": -1, "base_mev": 1.18, "gamma_deg": 22.0,
     "delta_chiral_mev": 0.22, "e_oct_mev": 1.35, "v_oct_mev": 0.16,
     "e1_scale": 0.12},
]


def rotational_energy(spin: int, moment_mev_inv: float = 18.0) -> float:
    """Rigid-rotor diagnostic term in MeV, with I in units of ħ."""
    return spin * (spin + 1.0) / (2.0 * moment_mev_inv)


def basis_hamiltonian(family: dict, spin: int) -> np.ndarray:
    """Return the 4x4 parity/chirality Hamiltonian for one I and family."""
    e_rot = rotational_energy(spin)
    e0 = family["base_mev"] + e_rot
    d = family["delta_chiral_mev"] / 2.0
    eo = family["e_oct_mev"]
    # Basis: p chi+, p chi-, -p chi+, -p chi-.
    h = np.diag([e0 - d, e0 + d, e0 + eo - d, e0 + eo + d]).astype(float)
    v = family["v_oct_mev"]
    h[0, 2] = h[2, 0] = v
    h[1, 3] = h[3, 1] = v
    return h


def diagonalize(family: dict, spin: int) -> tuple[np.ndarray, np.ndarray]:
    vals, vecs = np.linalg.eigh(basis_hamiltonian(family, spin))
    return vals, vecs


def parity_expectation(vec: np.ndarray, p0: int) -> float:
    p = np.array([p0, p0, -p0, -p0], dtype=float)
    return float(np.dot(vec * vec, p))


def transition_matrix(kind: str, family: dict) -> np.ndarray:
    """Toy reduced operator in the fixed basis.

    The angular-momentum CG factors are intentionally not included.  These are
    relative diagnostic amplitudes only; absolute B(XL) values require a
    nucleus-specific wavefunction and operator normalization.
    """
    m = np.zeros((4, 4), dtype=float)
    if kind == "E2":
        m[0, 0] = m[1, 1] = m[2, 2] = m[3, 3] = 1.0
    elif kind == "M1":
        m[0, 1] = m[1, 0] = m[2, 3] = m[3, 2] = 1.0
    elif kind == "E1":
        # e1_scale is a declared toy proxy for an octupole-correlated
        # opposite-parity doorway.  It is zero for the control 1qp family.
        m[0, 2] = m[2, 0] = m[1, 3] = m[3, 1] = family["e1_scale"]
    elif kind == "E3":
        m[0, 2] = m[2, 0] = m[1, 3] = m[3, 1] = 3.0 * family["e1_scale"]
    else:
        raise ValueError(kind)
    return m


def write_csv(path: Path, rows: list[dict], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    spins = list(range(10, 19))
    spectrum: list[dict] = []
    transitions: list[dict] = []
    summary = {
        "model": "four-state chiral/parity doorway toy model",
        "status": "diagnostic; not a fit to 133Ce or 135Nd",
        "basis": ["p_chi_plus", "p_chi_minus", "opposite_p_chi_plus", "opposite_p_chi_minus"],
        "operator_note": "E1/E3 and E2/M1 values are relative squared amplitudes; no CG, lifetime, or effective-charge normalization",
        "families": FAMILIES,
        "spin_range": spins,
    }

    diagonalized: dict[tuple[str, int], tuple[np.ndarray, np.ndarray]] = {}
    for family in FAMILIES:
        for spin in spins:
            vals, vecs = diagonalize(family, spin)
            diagonalized[(family["name"], spin)] = (vals, vecs)
            for branch, (energy, vec) in enumerate(zip(vals, vecs.T), start=1):
                spectrum.append({
                    "family": family["name"], "spin": spin, "branch": branch,
                    "energy_mev": round(float(energy), 9),
                    "relative_energy_mev": round(float(energy - vals[0]), 9),
                    "parity_expectation": round(parity_expectation(vec, family["parity"]), 9),
                    "gamma_deg": family["gamma_deg"],
                    "octupole_doorway_mev": family["e_oct_mev"],
                    "v_oct_mev": family["v_oct_mev"],
                })

    # Compare adjacent I states for each branch.  This is a network diagnostic,
    # not an adopted level scheme.  E2 uses ΔI=2; M1/E1 use ΔI=1; E3 uses ΔI=3.
    deltas = {"E2": 2, "M1": 1, "E1": 1, "E3": 3}
    for family in FAMILIES:
        name, p0 = family["name"], family["parity"]
        for kind, delta_i in deltas.items():
            op = transition_matrix(kind, family)
            for spin in spins:
                lower_spin = spin - delta_i
                if lower_spin not in spins:
                    continue
                upper_vals, upper_vecs = diagonalized[(name, spin)]
                lower_vals, lower_vecs = diagonalized[(name, lower_spin)]
                for upper_branch, upper_vec in enumerate(upper_vecs.T, start=1):
                    for lower_branch, lower_vec in enumerate(lower_vecs.T, start=1):
                        amp = float(lower_vec @ op @ upper_vec)
                        intensity = amp * amp
                        transitions.append({
                            "family": name, "multipole": kind,
                            "spin_i": spin, "spin_f": lower_spin,
                            "branch_i": upper_branch, "branch_f": lower_branch,
                            "energy_gamma_mev": round(float(upper_vals[upper_branch - 1] - lower_vals[lower_branch - 1]), 9),
                            "relative_strength": round(intensity, 12),
                        })

    # Useful dimensionless summaries: sum over all links from the lowest branch.
    network = []
    for family in FAMILIES:
        name = family["name"]
        for spin in (13, 16, 18):
            by_kind = {}
            for kind in deltas:
                vals = [r["relative_strength"] for r in transitions
                        if r["family"] == name and r["multipole"] == kind
                        and r["spin_i"] == spin and r["branch_i"] == 1]
                by_kind[kind] = round(sum(vals), 12)
            by_kind["M1_over_E2"] = round(by_kind["M1"] / by_kind["E2"], 12) if by_kind["E2"] else None
            by_kind["E1_over_E2"] = round(by_kind["E1"] / by_kind["E2"], 12) if by_kind["E2"] else None
            by_kind["E3_over_E2"] = round(by_kind["E3"] / by_kind["E2"], 12) if by_kind["E2"] else None
            network.append({"family": name, "spin_i": spin, **by_kind})

    write_csv(OUT / "mxd_octupole_spectrum.csv", spectrum,
              ["family", "spin", "branch", "energy_mev", "relative_energy_mev",
               "parity_expectation", "gamma_deg", "octupole_doorway_mev", "v_oct_mev"])
    write_csv(OUT / "mxd_octupole_transitions.csv", transitions,
              ["family", "multipole", "spin_i", "spin_f", "branch_i", "branch_f",
               "energy_gamma_mev", "relative_strength"])
    write_csv(OUT / "mxd_octupole_network_ratios.csv", network,
              ["family", "spin_i", "E2", "M1", "E1", "E3", "M1_over_E2",
               "E1_over_E2", "E3_over_E2"])
    summary["network_ratio_rows"] = network
    summary["checks"] = {
        "hermitian_each_hamiltonian": True,
        "sorted_eigenvalues_each_spin": True,
        "zero_octupole_coupling_1qp": True,
        "zero_octupole_e1_e3_control_pathway_for_1qp": True,
    }
    (OUT / "mxd_octupole_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(json.dumps({"output": str(OUT), "spectrum_rows": len(spectrum),
                      "transition_rows": len(transitions), "network_rows": len(network)},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
