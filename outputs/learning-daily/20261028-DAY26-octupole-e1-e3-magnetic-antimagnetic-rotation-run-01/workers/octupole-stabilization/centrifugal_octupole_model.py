def main() -> None:
    spins = list(range(0, 25))
    model = {}
    for nucleus, p in POTENTIALS.items():
        rows = []
        for spin in spins:
            x_min, e_min = minimize_on_grid(spin, p)
            beta = math.sqrt(max(x_min, 0.0))
            barrier = barrier_or_gain(spin, x_min, p)
            rows.append({
                "spin": spin,
                "L": spin * (spin + 1),
                "beta3_min": beta,
                "x_min": x_min,
                "v_eff_min_MeV": e_min,
                "central_barrier_or_gain_MeV": barrier,
                "delta_model_keV": 1000.0 * wkb_surrogate(beta, barrier, p),
                "dVeff_dx_at_min_MeV": dv_eff_dx(x_min, spin, p),
            })
        # The requested derivative identity is tested at an off-minimum point.
        x_test, i_test = 0.013, 12
        h = 1.0e-6
        finite = (v_eff(x_test + h, i_test, p) - v_eff(x_test - h, i_test, p)) / (2 * h)
        analytic = dv_eff_dx(x_test, i_test, p)
        model[nucleus] = {
            "parameters": p,
            "rows": rows,
            "derivative_check": {
                "spin": i_test,
                "x": x_test,
                "analytic_MeV": analytic,
                "finite_difference_MeV": finite,
                "absolute_error_MeV": abs(analytic - finite),
            },
            "experimental_delta_e_keV": parity_displacements(LEVELS_KEV[nucleus]),
            "experimental_locator": LEVELS_KEV[nucleus]["locator"],
        }

    payload = {
        "schema": "centrifugal-octupole-stabilization/v1",
        "status": "reproducible-schematic-model",
        "units": {"x": "dimensionless beta3^2", "beta3": "dimensionless",
                  "potential": "MeV", "delta_e": "keV"},
        "equations": {
            "effective_potential": "V_eff(x;I)=V0(x)+A*I*(I+1)/(1+c3*x)",
            "derivative": "dV_eff/dx=dV0/dx-A*I*(I+1)*c3/(1+c3*x)^2",
            "physical_form": "dV_eff/d(beta3^2)=dV0/d(beta3^2)-hbar^2*I*(I+1)/(2*J^2)*dJ/d(beta3^2)",
            "parity_surrogate": "deltaE=C exp[-s(beta3/beta_scale)^2 sqrt(Vbar/ZPE)]",
        },
        "interpretation": {
            "soft_Ba": "A centrifugal bifurcation creates and deepens a finite-beta3 minimum as I increases.",
            "static_Ra_Th": "A pre-existing double well is shifted outward and its central barrier grows.",
            "scope": "The model is illustrative; the parity-displacement curve is a WKB-like surrogate, not a microscopic prediction.",
        },
        "model": model,
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n")

    with OUT_CSV.open("w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["nucleus", "spin", "e_negative_keV", "positive_reference_keV", "delta_e_keV", "source_or_model"])
        for nucleus, levels in LEVELS_KEV.items():
            for row in parity_displacements(levels):
                writer.writerow([nucleus, row["spin"], row["e_negative_keV"],
                                 row["positive_reference_keV"], row["delta_e_keV"], "experimental-input"])
        for nucleus, data in model.items():
            for row in data["rows"]:
                writer.writerow([nucleus, row["spin"], "", "", row["delta_model_keV"], "schematic-model"])


if __name__ == "__main__":
    main()
