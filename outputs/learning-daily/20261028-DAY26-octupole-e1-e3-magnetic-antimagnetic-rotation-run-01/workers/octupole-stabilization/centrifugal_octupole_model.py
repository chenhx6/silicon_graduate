def parity_displacements(levels: dict) -> list[dict]:
    """Return delta E(I)=E(I-)-[E((I-1)+)+E((I+1)+)]/2 in keV."""
    positive = dict(levels["positive"])
    rows = []
    for spin, e_minus in levels["negative"]:
        if spin - 1 not in positive or spin + 1 not in positive:
            continue
        e_ref = 0.5 * (positive[spin - 1] + positive[spin + 1])
        rows.append({
            "spin": spin,
            "e_negative_keV": e_minus,
            "positive_reference_keV": e_ref,
            "delta_e_keV": e_minus - e_ref,
        })
    return rows


def v0(x: float, p: dict) -> float:
    """Bare potential in MeV; x=beta3^2 >= 0."""
    if p["kind"] == "soft":
        return p["k2"] * x + p["k4"] * x * x
    # A symmetric double well in beta3.  At x=0 its barrier is p['barrier'].
    return p["barrier"] * (1.0 - x / p["x0"]) ** 2


def dv0_dx(x: float, p: dict) -> float:
    if p["kind"] == "soft":
        return p["k2"] + 2.0 * p["k4"] * x
    return -2.0 * p["barrier"] / p["x0"] * (1.0 - x / p["x0"])


def j_factor(x: float, p: dict) -> float:
    return 1.0 + p["c3"] * x


def v_eff(x: float, spin: int, p: dict) -> float:
    L = spin * (spin + 1)
    return v0(x, p) + p["A"] * L / j_factor(x, p)


def dv_eff_dx(x: float, spin: int, p: dict) -> float:
    """Analytic derivative requested in the task."""
    L = spin * (spin + 1)
    J = j_factor(x, p)  # J=J0*J_factor; J0 cancels in this scaled form.
    dJ_dx = p["c3"]
    return dv0_dx(x, p) - p["A"] * L * dJ_dx / (J * J)


def minimize_on_grid(spin: int, p: dict) -> tuple[float, float]:
    """Robust derivative-free minimum over x>=0, followed by local refinement."""
    xmax = 0.16  # beta3 <= 0.4 covers the intended schematic domain.
    n = 16000
    dx = xmax / n
    best_i = min(range(n + 1), key=lambda i: v_eff(i * dx, spin, p))
    lo = max(0.0, (best_i - 2) * dx)
    hi = min(xmax, (best_i + 2) * dx)
    for _ in range(80):
        m1 = lo + (hi - lo) / 3.0
        m2 = hi - (hi - lo) / 3.0
        if v_eff(m1, spin, p) < v_eff(m2, spin, p):
            hi = m2
        else:
            lo = m1
    x = 0.5 * (lo + hi)
    return x, v_eff(x, spin, p)


def barrier_or_gain(spin: int, x_min: float, p: dict) -> float:
    """Effective central barrier/gain in MeV.

    For the soft potential the origin changes from a minimum to a maximum at
    the centrifugal bifurcation, so this is the central barrier only when
    positive.  For a static double well it is the central barrier relative to
    the selected minimum.
    """
    return max(0.0, v_eff(0.0, spin, p) - v_eff(x_min, spin, p))


def wkb_surrogate(beta: float, barrier: float, p: dict) -> float:
    """Descriptive parity-displacement surrogate in MeV.

    This is intentionally labeled a surrogate: it is not a GCM/EDF result.
    Increasing beta3 and central barrier decreases the parity splitting.
    """
    s = p["wkb_scale"] * (beta / p["beta_scale"]) ** 2
    s *= math.sqrt(max(barrier, 1.0e-9) / p["zpe"])
    return p["prefactor"] * math.exp(-s)


