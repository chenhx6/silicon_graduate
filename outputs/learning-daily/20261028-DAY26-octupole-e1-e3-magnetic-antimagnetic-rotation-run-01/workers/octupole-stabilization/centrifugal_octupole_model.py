#!/usr/bin/env python3
"""Minimal reproducible centrifugal-stabilization model for an octupole coordinate.

The script has two deliberately separate layers:

1. A one-dimensional effective potential
       V_eff(x; I) = V0(x) + A I(I+1)/(1+c3*x),  x = beta_3**2,
   with an analytic derivative and a finite-difference check.
2. A descriptive WKB-like parity-splitting surrogate.  It is not a fit to a
   microscopic EDF and is only used to show how a growing octupole minimum
   can drive an alternating-parity displacement toward zero.

The level energies below are recorded as inputs, not generated by this model.
All energies are in MeV internally (keV in the exported level table).
"""

