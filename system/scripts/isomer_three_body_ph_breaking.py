#!/usr/bin/env python3
"""Single-j pure three-body particle-hole symmetry breaking, dimensionless.

Determinants are ordered as in isomer_seniority_transfer_validation.py. The
unique J=27/2 three-fermion multiplet is generated by lowering the normalized
highest determinant. V3 is its second-quantized projector, with no normal-order
projection or lower-body additions. Run with BLAS threads fixed to one:
  PYTHONDONTWRITEBYTECODE=1 OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 \
    python3 system/scripts/isomer_three_body_ph_breaking.py --output outputs/l4/20261107-isomer-cross-region-round2/three-body/results.json
"""
import argparse
import hashlib
import itertools
import json
import math
import platform
import sys
from functools import lru_cache
from pathlib import Path

import numpy as np
import scipy
from scipy.linalg import null_space
import isomer_seniority_transfer_validation as old

N = 6
TWOJ3 = 27
ROOT = Path(__file__).resolve().parents[2]

def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()

@lru_cache(None)
def multiplet():
    # Three maximal magnetic substates: m=11/2,9/2,7/2.
    assert len(old.basis(3, TWOJ3)) == 1
    states = {TWOJ3: np.ones(1)}
    for tm in range(TWOJ3, -TWOJ3, -2):
        # J_-|J,M> = sqrt((J+M)(J-M+1)) |J,M-1>.
        coef = math.sqrt((TWOJ3 + tm) * (TWOJ3 - tm + 2)) / 2
        states[tm-2] = old.onebody(3, tm-2, 1, 'jplus').T @ states[tm] / coef
    return states

@lru_cache(None)
def triple(n, tm, triple_tm):
    """B_JM: n, M -> n-3, M-M3, with normalized 3-body coefficients."""
    src = old.basis(n, tm)
    dst = old.basis(n-3, tm-triple_tm)
    dindex = {s:k for k,s in enumerate(dst)}
    out = np.zeros((len(dst), len(src)))
    for state3, coefficient in zip(old.basis(3,triple_tm), multiplet()[triple_tm]):
        if abs(coefficient)<1e-15:
            continue
        indices = [i for i in range(12) if state3 >> i & 1]
        for k, s in enumerate(src):
            sign = 1
            for i in indices:
                x = old.annihilate(s, i)
                if x is None:
                    break
                s, sign1 = x
                sign *= sign1
            else:
                out[dindex[s],k] += coefficient * sign
    return out

@lru_cache(None)
def v3(tm):
    dim = len(old.basis(N,tm))
    out = np.zeros((dim,dim))
    for t in range(-TWOJ3,TWOJ3+1,2):
        b = triple(N,tm,t)
        out += b.T @ b
    return out

def block(J):
    tm=2*J
    jp=old.onebody(N,tm,1,'jplus')
    z=null_space(jp)
    h=old.ham(N,J,0.)
    v=v3(tm)
    eval0, u=np.linalg.eigh(z.T@h@z)
    ids=np.flatnonzero(np.abs(eval0+1)<1e-10)
    assert len(ids)==1, (J,eval0)
    ref=z@u[:,ids[0]]
    return {'J':J,'z':z,'h':h,'v':v,'ref':ref,'unperturbed_spectrum':eval0,
            'gap':min(abs(x+1) for x in eval0 if abs(x+1)>1e-9)}

def solve(b, lam, ref, control=False):
    J=b['J']; z=b['z']
    h=old.ham(N,J,lam) if control else b['h']+lam*b['v']
    en, u=np.linalg.eigh(z.T@h@z)
    vec=z@u
    k=int(np.argmax(abs(vec.T@ref)))
    v=vec[:,k]
    if v@ref < 0: v=-v
    return v,float(en[k]),float(np.linalg.norm(h@v-en[k]*v)),float(np.linalg.norm(old.onebody(N,2*J,1,'jplus')@v)),float((v@b['ref'])**2),float((v@ref)**2),float(min([abs(en[k]-en[i]) for i in range(len(en)) if i!=k],default=math.inf))

def components(vi,vf):
    vals=[]
    for m in (8,9,10):
        v=vi.copy()
        for mm in range(10,m,-1):
            v=old.onebody(N,2*(mm-1),1,'jplus').T@v/math.sqrt((10+mm)*(10-mm+1))
        q=8-m
        mat=old.onebody(N,2*m,q,'q')
        amp=float(vf@mat@v)
        w=old.w3j(16,4,20,-16,2*q,2*m)
        vals.append({'m_initial':m,'q':q,'amplitude':amp,'reduced_amplitude':amp/w,'strength':amp**2/(21*w*w)})
    return vals

def deriv(b):
    z=b['z']; h=b['h']; v=b['v']; ref=b['ref']
    en,u=np.linalg.eigh(z.T@h@z); states=z@u
    dv=np.zeros_like(ref)
    for e,vec in zip(en,states.T):
        if abs(e+1)>1e-9: dv+=vec*(vec@v@ref)/(-1-e)
    return dv

def reordered_check(vi,vf):
    v=vi.copy()
    for mm in (10,9):
        v=old.onebody(N,2*(mm-1),1,'jplus').T@v/math.sqrt((10+mm)*(10-mm+1))
    p=np.arange(len(v)-1,-1,-1)
    signs=np.array([old.phase((s & 0x555).bit_count()) for s in old.basis(N,16)])[p]
    q=old.onebody(N,16,0,'q')
    x=(vf[p]*signs)@(q[np.ix_(p,p)]*signs[:,None]*signs[None,:])@(v[p]*signs)
    return float(abs(x-vf@q@v))

def refined_endpoint(b, end, steps):
    ref=b['ref']
    for lam in np.linspace(0,end,steps+1)[1:]:
        ref=solve(b,float(lam),ref)[0]
    return ref

def rotated_resolvent_check(b):
    z=b['z']; en,u=np.linalg.eigh(z.T@b['h']@z); states=z@u
    original=deriv(b)
    out=np.zeros_like(original)
    # Rotate within each exactly degenerate energy subspace. QR is deterministic.
    for e in sorted(set(np.round(en,10))):
        mask=np.abs(en-e)<1e-9
        group=states[:,mask]
        e=float(np.mean(en[mask]))
        if abs(e+1)<1e-9: continue
        n=group.shape[1]
        matrix=np.fromfunction(lambda i,j: np.sin((i+1)*(j+2))+np.cos((i+2)*(j+1)),(n,n))
        rot,_=np.linalg.qr(matrix)
        rotated=group@rot
        out+=rotated@(rotated.T@b['v']@b['ref'])/(-1-e)
    return float(np.linalg.norm(out-original))

def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--output',required=True,type=Path); args=parser.parse_args()
    norms=[abs(np.linalg.norm(v)-1) for v in multiplet().values()]
    assert max(norms)<1e-12
    assert all(abs((triple(3,t,t)@triple(3,t,t).T).item()-1)<1e-12 for t in range(-27,28,2))
    checks=[]
    for tm in (16,18,20):
        v=v3(tm); vp=v3(tm+2); jp=old.onebody(N,tm,1,'jplus'); c=old.conjugation(N,tm)
        h=old.ham(N,tm//2,0); q=old.onebody(N,tm,0,'q')
        checks.append({'two_m':tm,'dimension':len(v),'hermiticity_frobenius':float(np.linalg.norm(v-v.T)),
                       'jplus_commutator_frobenius':float(np.linalg.norm(vp@jp-jp@v)),
                       'c_unitarity_frobenius':float(np.linalg.norm(c.T@c-np.eye(len(c)))),
                       'c_square_frobenius':float(np.linalg.norm(c@c-np.eye(len(c)))),
                       'h0_c_commutator_frobenius':float(np.linalg.norm(h@c-c@h)),
                       'v3_c_commutator_frobenius':float(np.linalg.norm(v@c-c@v)),
                       'c_odd_part_frobenius':float(np.linalg.norm((v-c.T@v@c)/2)),
                       'q20_c_odd_error_frobenius':float(np.linalg.norm(c.T@q@c+q)),
                       'v3_norm_frobenius':float(np.linalg.norm(v))})
    assert max(x['jplus_commutator_frobenius'] for x in checks)<1e-10
    assert max(x['hermiticity_frobenius'] for x in checks)<1e-12
    assert min(x['v3_c_commutator_frobenius'] for x in checks)>1e-5
    # A complete scalar two-body basis in one j shell consists of the six
    # normalized antisymmetric pair projectors J=0,2,4,6,8,10.
    two_body_checks=[]
    for tm in (16,20):
        c=old.conjugation(N,tm)
        for pair_j in range(0,12,2):
            dim=len(old.basis(N,tm)); h2=np.zeros((dim,dim))
            for pm in range(-pair_j,pair_j+1):
                a=old.pair(N,tm,pair_j,pm); h2+=a.T@a
            two_body_checks.append({'two_m':tm,'pair_J':pair_j,
                'C_commutator_frobenius':float(np.linalg.norm(h2@c-c@h2))})
    assert max(t['C_commutator_frobenius'] for t in two_body_checks)<1e-10
    b10,b8=block(10),block(8)
    assert b10['gap']>1e-5 and b8['gap']>1e-5
    v10,v8=b10['ref'],b8['ref']
    # First-order perturbation theory uses the resolvent on the complete orthogonal
    # fixed-J pairing eigenspace; no single v=4 basis vector is privileged.
    d10,d8=deriv(b10),deriv(b8)
    slope=components(d10,v8)[0]['amplitude']+components(v10,d8)[0]['amplitude']
    degeneracy_checks={'J10_rotated_resolvent_delta':rotated_resolvent_check(b10),
                       'J8_rotated_resolvent_delta':rotated_resolvent_check(b8)}
    assert max(degeneracy_checks.values())<1e-12
    refinement=[]
    for end in (-0.01,0.01):
        i20,f20=refined_endpoint(b10,end,20),refined_endpoint(b8,end,20)
        i40,f40=refined_endpoint(b10,end,40),refined_endpoint(b8,end,40)
        refinement.append({'endpoint':end,'steps_coarse':20,'steps_fine':40,
                           'J10_one_minus_overlap_squared':float(abs(1-(i20@i40)**2)),
                           'J8_one_minus_overlap_squared':float(abs(1-(f20@f40)**2)),
                           'B_absolute_difference':abs(components(i20,f20)[0]['strength']-components(i40,f40)[0]['strength'])})
    assert max(r['B_absolute_difference'] for r in refinement)<1e-16
    rows=[]
    lambdas=[0.,0.0001,0.0002,0.0005,0.001,0.002,0.005,0.01,0.02,0.05]
    for control in (False,True):
        for sign in (-1,1):
            ref10,ref8=v10,v8
            for value in lambdas:
                lam=sign*value
                vi,ei,ri,hi,oi,si,gi=solve(b10,lam,ref10,control)
                vf,ef,rf,hf,of,sf,gf=solve(b8,lam,ref8,control)
                ref10,ref8=vi,vf
                comp=components(vi,vf)
                werror=max(abs(x['reduced_amplitude']-comp[0]['reduced_amplitude']) for x in comp)
                checksym=reordered_check(vi,vf)
                assert werror<1e-11 and checksym<1e-12
                assert max(ri,rf,hi,hf)<1e-10
                rows.append({'model':'two_body_J2_control' if control else 'three_body_J27over2',
                    'lambda':lam,'energy_J10':ei,'energy_J8':ef,'E10_minus_E8':ei-ef,
                    'direction_10_to_8':'downward' if ei>ef+1e-12 else ('upward' if ei<ef-1e-12 else 'degenerate'),
                    'C_J10':float(vi@old.conjugation(N,20)@vi),'C_J8':float(vf@old.conjugation(N,16)@vf),
                    'overlap0_J10_squared':oi,'overlap0_J8_squared':of,'overlap_previous_J10_squared':si,'overlap_previous_J8_squared':sf,
                    'gap_J10':gi,'gap_J8':gf,'residual_max':max(ri,rf),'highest_weight_max':max(hi,hf),
                    'components':comp,'phase_reversal_strength_delta':abs(components(-vi,vf)[0]['strength']-comp[0]['strength']),
                    'basis_reorder_rephase_amplitude_delta':checksym,'WE_reduced_amplitude_max_delta':werror})
    assert min(r['overlap_previous_J10_squared'] for r in rows)>0.99
    assert min(r['overlap_previous_J8_squared'] for r in rows)>0.99
    assert max(r['components'][0]['strength'] for r in rows if r['model']=='two_body_J2_control')<1e-25
    h=0.0001
    row=lambda x: next(r for r in rows if r['model']=='three_body_J27over2' and r['lambda']==x)
    central=(row(h)['components'][0]['amplitude']-row(-h)['components'][0]['amplitude'])/(2*h)
    assert abs(slope-central)<1e-6, (slope,central)
    result={'model':'j=11/2, n=6, H0=-A00†A00, V3=sum B†(27/2,M)B(27/2,M), no C projection',
            'units':'dimensionless pairing-energy units and <j||Q2||j>=1','seed':None,
            'python':sys.version,'platform':platform.platform(),'numpy':np.__version__,'scipy':scipy.__version__,
            'operator_construction':'highest determinant (m=7/2,9/2,11/2); normalized J- descent; B annihilates three particles; sum B†B is normal-ordered pure three-body',
            'max_multiplet_normalization_error':max(norms),'max_three_particle_projector_error':max(abs((triple(3,t,t)@triple(3,t,t).T).item()-1) for t in range(-27,28,2)),
            'particle_number_conservation':'each B removes exactly three particles, B† restores three; V3 is block diagonal in N and vanishes on N<3',
            'fixed_J_h0_eigenvalues':{'J10':b10['unperturbed_spectrum'].tolist(),'J8':b8['unperturbed_spectrum'].tolist()},
            'fixed_J_h0_target_gaps':{'J10':b10['gap'],'J8':b8['gap']},
            'phase_convention':'independently choose overlaps with previous tracked state positive starting from H0 eigenvectors; only relative signed slopes within same run are meaningful',
            'first_order_amplitude_M8_q0':slope,
            'first_order_initial_state_contribution':components(d10,v8)[0]['amplitude'],
            'first_order_final_state_contribution':components(v10,d8)[0]['amplitude'],
            'degenerate_subspace_rotation_checks':degeneracy_checks,
            'tracking_step_refinement':refinement,'central_difference_h_0.0001':central,
            'first_order_B_coefficient':slope*slope/(21*old.w3j(16,4,20,-16,0,16)**2),
            'checks':checks,'complete_scalar_two_body_basis_C_checks':two_body_checks,'rows':rows}
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,indent=2,allow_nan=False)+'\n')
    print(json.dumps({'checks':checks,'slope':slope,'finite_difference':central,'B_coefficient':result['first_order_B_coefficient'],
                      'selected':[row(x) for x in (-0.01,-0.001,0.001,0.01)]},indent=2))

if __name__=='__main__': main()
