#!/usr/bin/env python3
"""Read-only QA for maintained scientific Markdown and TeX."""

import argparse
from collections import defaultdict
from dataclasses import asdict, dataclass
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SCOPES = ('.agents/skills', 'knowledge', 'system', 'outputs')
SUFFIXES = {'.md', '.markdown', '.tex', '.ltx'}
PATHSPECS = (*SCOPES, *(f':(top,glob)*{suffix}' for suffix in sorted(SUFFIXES)))
SKIP_DIRS = {'cache', 'tmp', 'node_modules', '__pycache__', 'generated', 'build', 'staging', 'fixtures'}
GENERATED = re.compile(rb'(?im)^\s*(?:<!--|%|#)\s*(?:auto[- ]?generated|generated by|do not edit: generated)\b')
CONTROL = re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f\ufffd]')
FRAGMENT = re.compile(r'(?<!\\)(?:\\a(?![A-Za-z])|\\\\a(?=\s*(?:[0-9$]|\\a)))')
TAB_ESCAPE = re.compile(r'\t(?:ext(?:bf|rm)?\{|heta\b|o\b|imes\b|an\b|ilde\b)')
DOUBLE_SUBSCRIPT = re.compile(r'(?<!\\)_(?:[A-Za-z0-9]|\{[^{}]*\})_(?=[A-Za-z0-9{\\])')
MATH_DELIMITER = re.compile(r'\$+|\\[()\[\]]')
FENCE = re.compile(r'^\s*(?:>\s*)*(?:(?:[-+*]|\d+[.)])\s+)?(`{3,}|~{3,})(.*)$')
LIST_PREFIX = re.compile(r'^\s*(?:[-+*]|\d+[.)])\s+')
TEX_MATH = re.compile(r'\\(begin|end)\{((?:equation|align|alignat|flalign|gather|multline|displaymath|math)\*?)\}')
TEX_VERBATIM = re.compile(r'\\begin\{(verbatim\*?|Verbatim|lstlisting|minted)\}')


@dataclass(frozen=True, order=True)
class Issue:
    path: str
    line: int
    code: str
    reason: str


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args], timeout=30)


def git_paths(root, *args):
    return [value.decode('utf-8', 'surrogateescape') for value in git(root, *args).split(b'\0') if value]


def in_scope(name):
    path = Path(name)
    parts = path.parts
    return (bool(parts) and not path.is_absolute() and '..' not in parts
            and path.suffix.lower() in SUFFIXES and not SKIP_DIRS.intersection(parts[:-1])
            and (len(parts) == 1 or any(name.startswith(scope + '/') for scope in SCOPES))
            and not re.search(r'(?:^|/)(?:workers|node_modules)/|\.frozen\.tex$', name))


def eligible(root, name):
    path = root / name
    return in_scope(name) and path.is_file() and not path.is_symlink() and path.resolve().is_relative_to(root)


def changed_paths(root):
    tracked = git_paths(root, 'diff', '--name-only', '--no-renames', '-z', 'HEAD', '--', *PATHSPECS)
    untracked = git_paths(root, 'ls-files', '--others', '--exclude-standard', '-z', '--', *PATHSPECS)
    return set(tracked) | set(untracked)


def all_paths(root):
    return set(git_paths(root, 'ls-files', '--cached', '--others', '--exclude-standard', '-z', '--', *PATHSPECS))


def escaped(text, pos):
    start = pos
    while pos and text[pos - 1] == '\\':
        pos -= 1
    return (start - pos) % 2 == 1


def mask_inline_code(line):
    runs = list(re.finditer(r'`+', line))
    result = list(line)
    i = 0
    while i < len(runs):
        start = runs[i]
        if escaped(line, start.start()):
            i += 1
            continue
        end = next((j for j in range(i + 1, len(runs)) if len(runs[j][0]) == len(start[0])), None)
        if end is None:
            i += 1
            continue
        # GitHub also supports $`...`$ for inline math with Markdown metacharacters.
        a, b = start.start(), runs[end].end()
        if a and line[a-1] == '$' and b < len(line) and line[b] == '$' and not escaped(line, a-1):
            result[a:start.end()] = '!' * len(start[0])
            result[runs[end].start():b] = '!' * len(runs[end][0])
        else:
            result[a:b] = ' ' * (b - a)
        i = end + 1
    return ''.join(result)


def markdown_lines(lines):
    """Keep physical line numbering while excluding metadata, comments and code."""
    front_end = 0
    if lines and lines[0].strip() == '---':
        front_end = next((i + 1 for i, line in enumerate(lines[1:], 1) if line in ('---', '...')), 0)
    fence = None
    comment = False
    for i, line in enumerate(lines):
        if i < front_end:
            yield '', None
            continue
        mark = FENCE.match(line)
        if fence:
            if mark and mark[1][0] == fence[0][0] and len(mark[1]) >= len(fence[0]) and not mark[2].strip():
                fence = None
                yield '', None
            else:
                yield (line, 'math') if fence[1] else ('', None)
            continue
        if mark and not comment:
            fence = (mark[1], mark[2].strip() == 'math')
            yield '', None
            continue
        pieces = []
        pos = 0
        code_mask = mask_inline_code(line)
        while pos < len(line):
            if comment:
                end = line.find('-->', pos)
                end = len(line) if end == -1 else end + 3
                pieces.append(' ' * (end - pos))
                comment = not line[:end].endswith('-->')
                pos = end
            else:
                start = code_mask.find('<!--', pos)
                if start == -1:
                    pieces.append(line[pos:])
                    break
                pieces.append(line[pos:start] + '    ')
                pos = start + 4
                comment = True
        yield ''.join(pieces), 'markdown'


def tex_lines(lines):
    verbatim = None
    for line in lines:
        if verbatim:
            if r'\end{' + verbatim + '}' in line:
                verbatim = None
            yield '', None
            continue
        cut = next((i for i, ch in enumerate(line) if ch == '%' and not escaped(line, i)), len(line))
        line = line[:cut]
        if match := TEX_VERBATIM.search(line):
            verbatim = match[1]
            if r'\end{' + verbatim + '}' in line[match.end():]:
                verbatim = None
            yield '', None
            continue
        yield re.sub(r'\\verb\*?([^\w\s]).*?\1', lambda m: ' ' * len(m[0]), line), 'tex'


def table_row(line):
    line = line.strip()
    line = re.sub(r'^(?:>\s*)+', '', line)
    line = LIST_PREFIX.sub('', line, count=1)
    cuts = [i for i, char in enumerate(line) if char == '|' and not escaped(line, i)]
    if not cuts:
        return None
    bounds = [-1, *cuts, len(line)]
    cells = [line[left+1:right].strip() for left, right in zip(bounds, bounds[1:])]
    if cuts[0] == 0:
        cells.pop(0)
    if cuts[-1] == len(line) - 1:
        cells.pop()
    return cells


def table_issues(rows, add):
    # Preserve raw inline code, math and wiki aliases: their pipes still split GFM cells.
    cells = [table_row(line) if mode == 'markdown' else None for line, mode in rows]
    end = 0
    for i in range(1, len(cells)):
        header, separator = cells[i-1], cells[i]
        if i < end or not header or not separator or not all(re.fullmatch(r':?-+:?', c) for c in separator):
            continue
        count = len(header)
        if len(separator) != count:
            add(i+1, 'TABLE_HEADER', f'header has {count} cells, separator has {len(separator)}')
        end = i + 1
        while end < len(cells) and cells[end] is not None:
            if len(cells[end]) != count:
                add(end+1, 'TABLE_ROW', f'expected {count} cells, found {len(cells[end])}; check literal pipes and displaced content')
            end += 1


def validate_expression(body, start, add):
    depth = 0
    for line_no, line in enumerate(body, start):
        if TAB_ESCAPE.search(line):
            add(line_no, 'TEX_TAB_ESCAPE', 'tab followed by a TeX command suffix; check the generating string')
        if DOUBLE_SUBSCRIPT.search(line):
            add(line_no, 'TEX_DOUBLE_SUBSCRIPT', 'consecutive subscripts need grouping or the intended single subscript')
        for i, char in enumerate(line):
            if char == '%' and not escaped(line, i):
                break
            if char not in '{}' or escaped(line, i):
                continue
            if char == '}' and depth == 0:
                add(line_no, 'MATH_BRACE', 'closing brace has no opening brace in this formula')
            else:
                depth += 1 if char == '{' else -1
    if depth:
        add(start, 'MATH_BRACE', f'{depth} unclosed opening brace(s) in formula')


def looks_like_formula(tail):
    return bool(re.match(r'\s*(?:\\[A-Za-z]|[A-Za-z](?=$|\W)|[\dA-Za-z]+[_{^=])', tail))


def math_issues(rows, add):
    pending = None
    math_fence = []
    fence_start = 0
    for line_no, (raw, mode) in enumerate(rows, 1):
        if mode == 'math':
            if not math_fence:
                fence_start = line_no
            math_fence.append(raw)
            if FRAGMENT.search(raw):
                add(line_no, 'TEX_FRAGMENT_A', r'found literal \a; restore the intended command from context')
            continue
        if math_fence:
            validate_expression(math_fence, fence_start, add)
            math_fence.clear()
        if mode is None:
            continue
        line = mask_inline_code(raw) if mode == 'markdown' else raw
        if FRAGMENT.search(line):
            add(line_no, 'TEX_FRAGMENT_A', r'found literal \a; restore the intended command from context')
        if pending and pending[0] in ('$','\\(') and not line.strip():
            if looks_like_formula(pending[2][0]):
                add(pending[1], 'MATH_UNCLOSED', f'unclosed {pending[0]} math delimiter')
            pending = None
        tokens = [(m.start(), m.end(), m[0]) for m in MATH_DELIMITER.finditer(line) if not escaped(line, m.start())]
        if mode == 'tex':
            tokens.extend((m.start(), m.end(), m[0]) for m in TEX_MATH.finditer(line) if not escaped(line, m.start()))
            tokens.sort()
        cursor = 0
        for a, b, token in tokens:
            before = line[a-1:a] if a else ''
            after = line[b:b+1]
            inline_open = token == '$' and after and (not after.isspace() or TAB_ESCAPE.match(line, b))
            opener = token in ('$$', r'\(', r'\[') or inline_open or token.startswith(r'\begin{')
            closer = token != '$' or (before and not before.isspace() and (mode == 'tex' or not after.isdigit()))
            if pending:
                opening, start, body = pending
                close = {'\\(': '\\)', '\\[': '\\]'}.get(opening, opening.replace(r'\begin{', r'\end{', 1))
                if token == close and closer:
                    body[-1] += line[cursor:a]
                    validate_expression(body, start, add)
                    pending = None
                    cursor = b
                    continue
                if token == '$' and opening != '$' and mode != 'tex':
                    add(line_no, 'MATH_NESTED_DOLLAR', f'unescaped single dollar inside {opening} math')
                if opening == '$' and (token == '$$' or (token == '$' and opener and not closer)):
                    if looks_like_formula(body[0] + line[cursor:a]):
                        add(start, 'MATH_UNCLOSED', 'unclosed inline dollar math delimiter')
                    pending = None
                else:
                    continue
            if opener:
                pending = (token, line_no, [''])
                cursor = b
            elif (token in (r'\)', r'\]') or token.startswith(r'\end{')) and (mode == 'tex' or a == 0):
                add(line_no, 'MATH_UNOPENED', f'{token} has no matching opener')
        if pending:
            pending[2][-1] += line[cursor:]
            pending[2].append('')
    if pending and (pending[0] != '$' or looks_like_formula(pending[2][0])):
        add(pending[1], 'MATH_UNCLOSED', f'unclosed {pending[0]} math delimiter')
    if math_fence:
        validate_expression(math_fence, fence_start, add)


def check_bytes(name, data):
    issues = set()

    def add(line, code, reason):
        issues.add(Issue(name, line, code, reason))

    try:
        text = data.decode('utf-8-sig')
    except UnicodeDecodeError as exc:
        add(data.count(b'\n', 0, exc.start) + 1, 'ENCODING', f'invalid UTF-8 at byte {exc.start}')
        return sorted(issues)
    lines = text.replace('\r\n', '\n').split('\n')
    for i, line in enumerate(lines, 1):
        for match in CONTROL.finditer(line):
            char = ord(match[0])
            add(i, 'BEL' if char == 7 else 'CONTROL_CHAR', f'U+{char:04X} at column {match.start()+1}')
        if '\r' in line:
            add(i, 'CONTROL_CHAR', 'bare CR within LF/CRLF input')
    is_tex = Path(name).suffix.lower() in {'.tex', '.ltx'}
    rows = list((tex_lines if is_tex else markdown_lines)(lines))
    if not is_tex:
        table_issues(rows, add)
    math_issues(rows, add)
    return sorted(issues)


def scan(root, names):
    inspected, skipped, issues = [], [], []
    for name in sorted(set(names)):
        if not eligible(root, name):
            continue
        try:
            data = (root / name).read_bytes()
        except OSError as exc:
            issues.append(Issue(name, 1, 'READ_FAILED', str(exc)))
            continue
        if GENERATED.search(data[:2048]):
            skipped.append(name)
            continue
        inspected.append(name)
        issues.extend(check_bytes(name, data))
    return {'files': inspected, 'generated_skipped': skipped, 'issues': issues}


def check_render(root, names):
    """Locate formulas Pandoc parsed but could not turn into MathML."""
    if not shutil.which('pandoc'):
        raise RuntimeError('Pandoc is required for --render')
    issues = []
    for name in names:
        if Path(name).suffix.lower() not in {'.md', '.markdown'}:
            continue
        try:
            text = (root / name).read_text(encoding='utf-8-sig')
        except UnicodeDecodeError:
            continue
        result = subprocess.run(
            ['pandoc', '--sandbox', '-f', 'gfm+sourcepos', '-t', 'html', '--mathml'],
            input=text, encoding='utf-8', capture_output=True, timeout=30,
        )
        if result.returncode:
            issues.append(Issue(name, 1, 'PANDOC_ERROR', result.stderr.strip()))
            continue
        fallbacks = re.finditer(
            r'<span\s+data-pos="(\d+):[^"]+"[^>]*>\s*<span\s+class="math (?:inline|display)">',
            result.stdout,
        )
        issues.extend(Issue(name, int(m[1]), 'MATH_RENDER', 'Pandoc could not convert this formula to MathML')
                      for m in fallbacks)
    return issues


def summary(result):
    counts = defaultdict(int)
    for issue in result['issues']:
        counts[issue.code] += 1
    return f"{len(result['files'])} file(s), {len(result['issues'])} issue(s)" + (
        ' (' + ', '.join(f'{code}={counts[code]}' for code in sorted(counts)) + ')' if counts else '')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    selection = parser.add_mutually_exclusive_group()
    selection.add_argument('--all', action='store_true', help='scan all maintained documents')
    selection.add_argument('--changed', action='store_true', help='scan staged, unstaged and untracked documents')
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--format', choices=('text', 'json'), default='text')
    parser.add_argument('--render', action='store_true', help='also check Pandoc MathML conversion (Markdown only)')
    parser.add_argument('paths', nargs='*')
    args = parser.parse_args()
    root = args.root.resolve()
    if args.paths and (args.all or args.changed):
        parser.error('choose explicit paths, --all, or --changed')
    try:
        if args.paths:
            names = [Path(path).as_posix() for path in args.paths]
            if invalid := [name for name in names if not eligible(root, name)]:
                parser.error('outside document QA scope or missing: ' + ', '.join(invalid))
        else:
            names = all_paths(root) if args.all else changed_paths(root)
    except (OSError, subprocess.SubprocessError) as exc:
        parser.error(f'cannot determine document scope: {exc}')
    result = scan(root, names)
    if args.render:
        try:
            result['issues'] = sorted(result['issues'] + check_render(root, result['files']))
        except (RuntimeError, subprocess.TimeoutExpired) as exc:
            parser.error(str(exc))
    if args.format == 'json':
        print(json.dumps({**result, 'issues': [asdict(i) for i in result['issues']]}, ensure_ascii=True, indent=2))
    else:
        for issue in result['issues']:
            print(f'{issue.path}:{issue.line}: {issue.code}: {issue.reason}')
        print(summary(result))
    return int(bool(result['issues']))


if __name__ == '__main__':
    sys.exit(main())
