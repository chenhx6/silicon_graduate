#!/usr/bin/env python3
"""
isobaric_analog_state_ced_calculator.py
======================================
Isobaric Analog State (IAS) Coulomb Displacement Energy & Coulomb Energy
Difference (CED) High-Spin Alignment Analyzer.

Physics & Formulation:
----------------------
1. Isobaric Analog State (IAS):
   Generated by Fermi isospin operator T_- = sum_k tau_-(k):
     |IAS> = (1 / sqrt(2*T_0)) * T_- |Parent>
   Shares identical spatial-spin structure as parent state, with T = T_0, T_z = T_0 - 1.

2. Coulomb Displacement Energy Delta_E_C:
   Delta_E_C = E(IAS) - E(Parent_GS) = M(Z+1, A) - M(Z, A) + Delta_nH
   Standard parameterization (Janecke / Anderson):
     Delta_E_C(Z, A) = 1.444 * (Z_bar / A^(1/3)) - 1.130 MeV
     where Z_bar = Z + 0.5.

3. Coulomb Energy Difference (CED) along Mirror Bands:
   CED(I) = E_x(I, T_z = -1/2) - E_x(I, T_z = +1/2)
   - When valence protons align into identical orbitals at crossing spin I_c,
     their mutual Coulomb repulsion increases by Delta_E_coul ~ +100 keV.
   - For valence neutrons, Coulomb interaction is zero.
   - A sharp jump in CED(I) provides definitive proof of proton vs neutron alignment!

References:
  - A. Bohr and B. R. Mottelson, Nuclear Structure, Vol. I, Benjamin (1969).
  - J. Janecke, in Isospin in Nuclear Physics, ed. D. H. Wilkinson (1969).
  - M. A. Bentley and P. E. Garrett, J. Phys. G: Nucl. Part. Phys. 34, R182 (2007).
  - 卢希庭, 《原子核物理（修订版）》, 第3章 核力与同位旋.
"""

import math
import json
import argparse
import sys
from typing import Dict, Any, List, Optional, Tuple


def calculate_coulomb_displacement_energy(
    Z_parent: int,
    A_mass: int,
    r0_fm: float = 1.20
) -> Dict[str, float]:
    """
    Computes Coulomb displacement energy Delta_E_C between parent ground state
    and Isobaric Analog State (IAS) in daughter (Z+1, A).
    """
    Z_bar = Z_parent + 0.5
    A13 = A_mass ** (1.0 / 3.0)

    # 1. Classical Coulomb sphere with exchange (Janecke formula)
    # E_coul = (3/5) * (e^2 / R) * [Z^2 - 0.76 * Z^(4/3)]
    # Differential dE_coul / dZ:
    e2_over_r0 = 1.440 / r0_fm  # MeV
    delta_ec_direct = (1.2 * e2_over_r0 / A13) * Z_bar
    delta_ec_exchange = - 0.96 * e2_over_r0 * (Z_bar ** (1.0 / 3.0)) / A13

    # Empirical fit formula Delta_E_C = 1.444 * (Z_bar / A^(1/3)) - 1.130 MeV
    delta_ec_empirical = 1.444 * (Z_bar / A13) - 1.130

    # IAS excitation energy in daughter nucleus
    # M(Z+1, A) - M(Z, A) = Delta_E_C - Delta_nH (where Delta_nH = 0.782 MeV)
    q_ec_decay = delta_ec_empirical - 0.7823

    return {
        "parent_Z": Z_parent,
        "daughter_Z": Z_parent + 1,
        "A_mass": A_mass,
        "Z_bar": Z_bar,
        "Coulomb_displacement_empirical_MeV": round(delta_ec_empirical, 3),
        "Coulomb_direct_term_MeV": round(delta_ec_direct, 3),
        "Coulomb_exchange_term_MeV": round(delta_ec_exchange, 3),
        "IAS_effective_Q_value_MeV": round(q_ec_decay, 3)
    }


def analyze_mirror_ced_sequence(
    spins: List[float],
    energies_proton_rich: List[float],  # E_x in keV for T_z = -1/2 (e.g. 49Mn)
    energies_neutron_rich: List[float]   # E_x in keV for T_z = +1/2 (e.g. 49Cr)
) -> Dict[str, Any]:
    """
    Analyzes Coulomb Energy Difference CED(I) across mirror rotational bands:
    CED(I) = E_x(I, Tz = -1/2) - E_x(I, Tz = +1/2).
    Identifies proton vs neutron band-crossing alignment jumps.
    """
    if len(spins) != len(energies_proton_rich) or len(spins) != len(energies_neutron_rich):
        raise ValueError("Length mismatch in CED inputs")

    ced_profile = []
    max_jump = 0.0
    jump_spin = spins[0]

    prev_ced = None
    for I, ep, en in zip(spins, energies_proton_rich, energies_neutron_rich):
        ced_val = ep - en  # in keV
        d_ced = (ced_val - prev_ced) if prev_ced is not None else 0.0

        if abs(d_ced) > abs(max_jump):
            max_jump = d_ced
            jump_spin = I

        ced_profile.append({
            "spin_I": I,
            "E_proton_rich_keV": ep,
            "E_neutron_rich_keV": en,
            "CED_keV": round(ced_val, 1),
            "Delta_CED_keV": round(d_ced, 1)
        })
        prev_ced = ced_val

    if max_jump > 30.0:
        alignment_diagnosis = f"Proton Pair Alignment (CED jumps up by {max_jump:+.1f} keV at I = {jump_spin} hbar due to increased proton-proton Coulomb repulsion)"
    elif max_jump < -30.0:
        alignment_diagnosis = f"Neutron Pair Alignment (CED drops by {max_jump:+.1f} keV at I = {jump_spin} hbar)"
    else:
        alignment_diagnosis = "Smooth Collective Rotation (No abrupt single-particle alignment jump)"

    return {
        "num_states": len(spins),
        "maximum_CED_jump_keV": round(max_jump, 1),
        "alignment_crossing_spin_I": jump_spin,
        "diagnosis": alignment_diagnosis,
        "ced_data": ced_profile
    }


def format_text_report(summary: Dict[str, Any]) -> str:
    lines = []
    lines.append("=" * 72)
    lines.append("   ISOBARIC ANALOG STATE (IAS) & MIRROR CED ALIGNMENT ANALYZER")
    lines.append("=" * 72)

    if "displacement_energy" in summary:
        de = summary["displacement_energy"]
        lines.append(f" ISOBARIC ANALOG STATE: Parent Z={de['parent_Z']} -> Daughter Z={de['daughter_Z']}, A={de['A_mass']}")
        lines.append(f"   Effective Z_bar                : {de['Z_bar']}")
        lines.append(f"   Coulomb Displacement Delta_E_C: {de['Coulomb_displacement_empirical_MeV']} MeV")
        lines.append(f"   Direct Coulomb Term            : {de['Coulomb_direct_term_MeV']} MeV")
        lines.append(f"   Exchange Term (Pauli)          : {de['Coulomb_exchange_term_MeV']} MeV")
        lines.append(f"   IAS Q-Value (M_d - M_p)        : {de['IAS_effective_Q_value_MeV']} MeV")
        lines.append("-" * 72)

    if "mirror_ced" in summary:
        ced = summary["mirror_ced"]
        lines.append(" COULOMB ENERGY DIFFERENCE (CED) ROTATIONAL ALIGNMENT:")
        lines.append(f"   Diagnosis                      : {ced['diagnosis']}")
        lines.append(f"   Band-Crossing Spin I_c         : {ced['alignment_crossing_spin_I']} hbar (Max Jump = {ced['maximum_CED_jump_keV']} keV)")
        lines.append("   " + "-" * 56)
        lines.append(f"   {'Spin I':<8} {'E(Tz=-1/2)':<14} {'E(Tz=+1/2)':<14} {'CED (keV)':<12} {'Delta_CED':<12}")
        lines.append("   " + "-" * 56)
        for pt in ced["ced_data"]:
            lines.append(f"   {pt['spin_I']:<8} {pt['E_proton_rich_keV']:<14.1f} {pt['E_neutron_rich_keV']:<14.1f} {pt['CED_keV']:<12.1f} {pt['Delta_CED_keV']:<12.1f}")
        lines.append("-" * 72)

    lines.append(" Physical Significance:")
    lines.append("   - Coulomb displacement Delta_E_C measures nuclear charge radius and IAS energy.")
    lines.append("   - CED(I) jumps isolate whether proton or neutron pairs align at backbending.")
    lines.append("   - Hallmark observable for isospin symmetry breaking in N ~ Z nuclei.")
    lines.append("========================================================================")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Isobaric Analog State (IAS) & Mirror CED Analyzer."
    )
    parser.add_argument("-Z", type=int, default=24, help="Parent proton number Z (default: 24 for Cr)")
    parser.add_argument("-A", type=int, default=49, help="Mass number A (default: 49 for 49Cr/49Mn)")
    parser.add_argument("--demo-ced", action="store_true", help="Run benchmark CED mirror analysis (49Mn vs 49Cr)")
    parser.add_argument("--spins", type=str, default=None, help="Comma-separated spins for custom CED")
    parser.add_argument("--e-p-rich", type=str, default=None, help="Comma-separated energies for Tz = -1/2 in keV")
    parser.add_argument("--e-n-rich", type=str, default=None, help="Comma-separated energies for Tz = +1/2 in keV")
    parser.add_argument("--json", action="store_true", help="Output results in JSON format")

    args = parser.parse_args()

    de_res = calculate_coulomb_displacement_energy(args.Z, args.A)
    summary = {"displacement_energy": de_res}

    if args.demo_ced or (args.spins is None and args.Z == 24 and args.A == 49):
        # Classic 49Mn vs 49Cr mirror band data (Bentley & Garrett 2007)
        spins = [3.5, 5.5, 7.5, 9.5, 11.5, 13.5, 15.5, 17.5]
        ep = [261.0, 1073.0, 1982.0, 3173.0, 4679.0, 6420.0, 8350.0, 10450.0]
        en = [272.0, 1083.0, 1970.0, 3130.0, 4580.0, 6380.0, 8340.0, 10460.0]
        ced_res = analyze_mirror_ced_sequence(spins, ep, en)
        summary["mirror_ced"] = ced_res
    elif args.spins and args.e_p_rich and args.e_n_rich:
        spins = [float(x.strip()) for x in args.spins.split(",")]
        ep = [float(x.strip()) for x in args.e_p_rich.split(",")]
        en = [float(x.strip()) for x in args.e_n_rich.split(",")]
        ced_res = analyze_mirror_ced_sequence(spins, ep, en)
        summary["mirror_ced"] = ced_res

    if args.json:
        print(json.dumps(summary, indent=2))
    else:
        print(format_text_report(summary))


if __name__ == "__main__":
    main()
